# Get neighbors from explicit config YAML
# Usage: get_neighbors_from_config <config_file> <device_index>
# Output: Space-separated list of neighbor interfaces
get_neighbors_from_config() {
    local config_file="$1"
    local device_index="$2"

    local neighbor_count=$(yq eval ".frr_config.devices[$device_index].neighbors | length" "$config_file" 2>/dev/null || echo "0")
    local neighbors=""

    for i in $(seq 0 $((neighbor_count - 1))); do
        local iface=$(yq eval ".frr_config.devices[$device_index].neighbors[$i].interface" "$config_file")
        if [[ -n "$iface" && "$iface" != "null" ]]; then
            neighbors="$neighbors $iface"
        fi
    done

    echo "$neighbors" | xargs  # Trim whitespace
}

# Get neighbors from VDC cabling configuration
# Usage: get_neighbors_from_vdc_cabling <vdc_config_file> <device_name>
# Output: Space-separated list of neighbor interfaces
get_neighbors_from_vdc_cabling() {
    local vdc_config="$1"
    local device_name="$2"

    local cable_count=$(yq eval '.cabling | length' "$vdc_config" 2>/dev/null || echo "0")
    local neighbors=""

    for i in $(seq 0 $((cable_count - 1))); do
        local src_device=$(yq eval ".cabling[$i].source.device" "$vdc_config")
        local src_iface=$(yq eval ".cabling[$i].source.interface" "$vdc_config")
        local dst_device=$(yq eval ".cabling[$i].destination.device" "$vdc_config")
        local dst_iface=$(yq eval ".cabling[$i].destination.interface" "$vdc_config")

        # Check if this device is involved in this cable
        if [[ "$src_device" == "$device_name" ]]; then
            neighbors="$neighbors $src_iface"
        elif [[ "$dst_device" == "$device_name" ]]; then
            neighbors="$neighbors $dst_iface"
        fi
    done

    echo "$neighbors" | xargs  # Trim whitespace
}

# Get device info from VDC topology
# Usage: get_vdc_device_info <vdc_config_file> <device_name>
# Output: JSON object with device info
get_vdc_device_info() {
    local vdc_config="$1"
    local device_name="$2"

    # Check hypervisors
    local hv_count=$(yq eval '.hypervisors | length' "$vdc_config" 2>/dev/null || echo "0")
    for i in $(seq 0 $((hv_count - 1))); do
        local name=$(yq eval ".hypervisors[$i].name" "$vdc_config")
        if [[ "$name" == "$device_name" ]]; then
            yq eval ".hypervisors[$i] | .type = \"hypervisor\"" "$vdc_config"
            return 0
        fi
    done

    # Check leaf switches
    local leaf_count=$(yq eval '.switches.leaf | length' "$vdc_config" 2>/dev/null || echo "0")
    for i in $(seq 0 $((leaf_count - 1))); do
        local name=$(yq eval ".switches.leaf[$i].name" "$vdc_config")
        if [[ "$name" == "$device_name" ]]; then
            yq eval ".switches.leaf[$i] | .type = \"switch\"" "$vdc_config"
            return 0
        fi
    done

    # Check spine switches
    local spine_count=$(yq eval '.switches.spine | length' "$vdc_config" 2>/dev/null || echo "0")
    for i in $(seq 0 $((spine_count - 1))); do
        local name=$(yq eval ".switches.spine[$i].name" "$vdc_config")
        if [[ "$name" == "$device_name" ]]; then
            yq eval ".switches.spine[$i] | .type = \"switch\"" "$vdc_config"
            return 0
        fi
    done

    # Check superspine switches
    local superspine_count=$(yq eval '.switches.superspine | length' "$vdc_config" 2>/dev/null || echo "0")
    for i in $(seq 0 $((superspine_count - 1))); do
        local name=$(yq eval ".switches.superspine[$i].name" "$vdc_config")
        if [[ "$name" == "$device_name" ]]; then
            yq eval ".switches.superspine[$i] | .type = \"switch\"" "$vdc_config"
            return 0
        fi
    done

    return 1
}

# List all devices from VDC topology
# Usage: list_vdc_devices <vdc_config_file>
# Output: One device name per line
list_vdc_devices() {
    local vdc_config="$1"

    # List hypervisors
    yq eval '.hypervisors[].name' "$vdc_config" 2>/dev/null || true

    # List leaf switches
    yq eval '.switches.leaf[].name' "$vdc_config" 2>/dev/null || true

    # List spine switches
    yq eval '.switches.spine[].name' "$vdc_config" 2>/dev/null || true

    # List superspine switches
    yq eval '.switches.superspine[].name' "$vdc_config" 2>/dev/null || true
}

