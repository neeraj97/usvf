# Wait for SSH to become available
# Usage: wait_for_ssh <host> <ssh_key_or_password> <auth_type> [max_attempts] [user]
# Returns: 0 if successful, 1 if timeout
wait_for_ssh() {
    local host="$1"
    local auth_credential="$2"
    local auth_type="${3:-key}"  # "key" or "password"
    local max_attempts="${4:-30}"
    local user="${5:-ubuntu}"
    local attempt=0

    frr_log_info "Waiting for SSH on $host..."

    while [[ $attempt -lt $max_attempts ]]; do
        if [[ "$auth_type" == "key" ]]; then
            if ssh -i "$auth_credential" \
                   -o StrictHostKeyChecking=no \
                   -o UserKnownHostsFile=/dev/null \
                   -o ConnectTimeout=5 \
                   -o BatchMode=yes \
                   "${user}@${host}" "echo ready" &>/dev/null; then
                frr_log_success "SSH available on $host"
                return 0
            fi
        else
            if sshpass -p "$auth_credential" ssh \
                   -o StrictHostKeyChecking=no \
                   -o UserKnownHostsFile=/dev/null \
                   -o ConnectTimeout=5 \
                   "${user}@${host}" "echo ready" &>/dev/null; then
                frr_log_success "SSH available on $host"
                return 0
            fi
        fi

        attempt=$((attempt + 1))
        sleep 10
    done

    frr_log_error "SSH timeout on $host after $max_attempts attempts"
    return 1
}

# Deploy FRR configuration to remote device
# Usage: ssh_deploy_frr_config <host> <auth_credential> <auth_type> <frr_config_content> [user]
# Note: Router ID is configured in frr.conf itself (interface lo1 section)
# Returns: 0 if successful, 1 if failed
ssh_deploy_frr_config() {
    local host="$1"
    local auth_credential="$2"
    local auth_type="${3:-key}"
    local frr_config="$4"
    local user="${5:-ubuntu}"

    frr_log_info "Deploying FRR configuration to $host..."

    # Create temporary file with config
    local temp_config=$(mktemp)
    echo "$frr_config" > "$temp_config"

    local ssh_opts="-o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null"
    local result=0

    # Build the deployment script
    # Note: Router ID on lo1 is configured in frr.conf itself (interface lo1 section)
    # FRR/zebra will apply it automatically on restart/reboot
    local deploy_script="
sudo cp /tmp/frr.conf /etc/frr/frr.conf
sudo chown frr:frr /etc/frr/frr.conf
sudo chmod 640 /etc/frr/frr.conf
sudo systemctl restart frr
sleep 3
echo ''
echo 'Router ID on lo1 (managed by FRR):'
ip addr show lo1 2>/dev/null | grep -E 'inet ' || echo '  (waiting for FRR to apply...)'
echo ''
echo 'BGP Summary:'
sudo vtysh -c 'show bgp summary' | head -20
"

    if [[ "$auth_type" == "key" ]]; then
        # Copy config file
        scp $ssh_opts -i "$auth_credential" "$temp_config" "${user}@${host}:/tmp/frr.conf" 2>/dev/null

        # Apply configuration
        ssh $ssh_opts -i "$auth_credential" "${user}@${host}" "$deploy_script" 2>&1
        result=$?
    else
        # Password auth (requires sshpass)
        sshpass -p "$auth_credential" scp $ssh_opts "$temp_config" "${user}@${host}:/tmp/frr.conf" 2>/dev/null

        sshpass -p "$auth_credential" ssh $ssh_opts "${user}@${host}" "$deploy_script" 2>&1
        result=$?
    fi

    rm -f "$temp_config"

    if [[ $result -eq 0 ]]; then
        frr_log_success "FRR configuration deployed to $host"
    else
        frr_log_error "Failed to deploy FRR configuration to $host"
    fi

    return $result
}

# Deploy FRR daemons configuration to remote device
# Usage: ssh_deploy_frr_daemons <host> <auth_credential> <auth_type> [user]
ssh_deploy_frr_daemons() {
    local host="$1"
    local auth_credential="$2"
    local auth_type="${3:-key}"
    local user="${4:-ubuntu}"

    frr_log_info "Deploying FRR daemons configuration to $host..."

    local daemons_config=$(generate_frr_daemons_config)
    local temp_config=$(mktemp)
    echo "$daemons_config" > "$temp_config"

    local ssh_opts="-o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null"
    local result=0

    if [[ "$auth_type" == "key" ]]; then
        scp $ssh_opts -i "$auth_credential" "$temp_config" "${user}@${host}:/tmp/daemons" 2>/dev/null
        ssh $ssh_opts -i "$auth_credential" "${user}@${host}" "sudo cp /tmp/daemons /etc/frr/daemons && sudo chown frr:frr /etc/frr/daemons" 2>/dev/null
        result=$?
    else
        sshpass -p "$auth_credential" scp $ssh_opts "$temp_config" "${user}@${host}:/tmp/daemons" 2>/dev/null
        sshpass -p "$auth_credential" ssh $ssh_opts "${user}@${host}" "sudo cp /tmp/daemons /etc/frr/daemons && sudo chown frr:frr /etc/frr/daemons" 2>/dev/null
        result=$?
    fi

    rm -f "$temp_config"
    return $result
}

# Verify FRR status on remote device
# Usage: ssh_verify_frr_status <host> <auth_credential> <auth_type> [user]
# Output: BGP summary
ssh_verify_frr_status() {
    local host="$1"
    local auth_credential="$2"
    local auth_type="${3:-key}"
    local user="${4:-ubuntu}"

    frr_log_info "Verifying FRR status on $host..."

    local ssh_opts="-o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null"

    if [[ "$auth_type" == "key" ]]; then
        ssh $ssh_opts -i "$auth_credential" "${user}@${host}" "sudo vtysh -c 'show bgp summary'" 2>/dev/null
    else
        sshpass -p "$auth_credential" ssh $ssh_opts "${user}@${host}" "sudo vtysh -c 'show bgp summary'" 2>/dev/null
    fi
}

