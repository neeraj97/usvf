}

# Generate complete FRR configuration
# Usage: generate_frr_config <device_name> <router_id> <asn> <neighbors> [options]
# Parameters:
#   device_name  - Hostname for the device
#   router_id    - BGP router ID (e.g., 10.1.0.1)
#   asn          - BGP AS number
#   neighbors    - Space-separated list of neighbor interfaces (e.g., "enp2s0 enp3s0")
#   options      - Optional JSON object with additional settings
# Output: Writes FRR config to stdout
#
# Environment variables (can be used instead of options):
#   FRR_VERSION              - FRR version string (default: 10.0)
#   FRR_PEER_GROUP           - BGP peer group name (default: FABRIC)
#   FRR_REDISTRIBUTE         - Redistribution type (default: connected)
#   FRR_REDISTRIBUTE_ROUTE_MAP - Route-map for redistribution (default: none)
#   FRR_REDISTRIBUTE_INTERFACES - Space-separated list of interfaces to match in route-map
#                                 (default: "lo1 dum-ex" for hypervisors, empty for switches)
generate_frr_config() {
    local device_name="$1"
    local router_id="$2"
    local asn="$3"
    local neighbors="$4"
    local options="${5:-}"

    # Parse options (defaults)
    local frr_version="${FRR_VERSION:-10.0}"
    local peer_group="${FRR_PEER_GROUP:-FABRIC}"
    local redistribute_type="${FRR_REDISTRIBUTE:-connected}"
    local redistribute_route_map="${FRR_REDISTRIBUTE_ROUTE_MAP:-}"
    local redistribute_interfaces="${FRR_REDISTRIBUTE_INTERFACES:-}"

    # Parse options JSON if provided
    if [[ -n "$options" ]]; then
        frr_version=$(echo "$options" | yq eval '.frr_version // "10.0"' - 2>/dev/null || echo "10.0")
        peer_group=$(echo "$options" | yq eval '.peer_group // "FABRIC"' - 2>/dev/null || echo "FABRIC")
        redistribute_type=$(echo "$options" | yq eval '.redistribute_type // "connected"' - 2>/dev/null || echo "connected")
        redistribute_route_map=$(echo "$options" | yq eval '.redistribute_route_map // ""' - 2>/dev/null || echo "")
        # redistribute_interfaces can be a YAML array or space-separated string
        local ri_raw=$(echo "$options" | yq eval '.redistribute_interfaces // ""' - 2>/dev/null || echo "")
        if [[ -n "$ri_raw" && "$ri_raw" != "null" ]]; then
            # Check if it's an array (starts with -)
            if echo "$ri_raw" | grep -q "^-"; then
                redistribute_interfaces=$(echo "$options" | yq eval '.redistribute_interfaces | join(" ")' - 2>/dev/null || echo "")
            else
                redistribute_interfaces="$ri_raw"
            fi
        fi
    fi

    # Start generating config
    cat <<EOF
!
! FRRouting configuration for $device_name
! Generated by FRR Configuration Module
!
frr version $frr_version
frr defaults traditional
hostname $device_name
log syslog informational
service integrated-vtysh-config
!
! Configure lo1 with router ID (managed by FRR, applied on restart/reboot)
interface lo1
 ip address $router_id/32
 description BGP Router ID
!
! BGP Configuration with Unnumbered Support
router bgp $asn
 bgp router-id $router_id
 bgp log-neighbor-changes
 bgp bestpath as-path multipath-relax
 no bgp default ipv4-unicast
 no bgp ebgp-requires-policy
 !
 ! Fabric peer-group for unnumbered BGP
 neighbor $peer_group peer-group
 neighbor $peer_group remote-as external
 neighbor $peer_group capability extended-nexthop
 !
EOF

    # Add BGP neighbors
    for neighbor in $neighbors; do
        cat <<EOF
 ! BGP neighbor on $neighbor
 neighbor $neighbor interface peer-group $peer_group
 !
EOF
    done

    # Address family configuration
    cat <<EOF
 address-family ipv4 unicast
  neighbor $peer_group activate
  neighbor $peer_group route-map ALLOW-ALL in
  neighbor $peer_group route-map ALLOW-ALL out
EOF

    # Add redistribution
    if [[ -n "$redistribute_route_map" ]]; then
        cat <<EOF
  redistribute $redistribute_type route-map $redistribute_route_map
EOF
    else
        cat <<EOF
  redistribute $redistribute_type
EOF
    fi

    cat <<EOF
  maximum-paths 64
  maximum-paths ibgp 64
 exit-address-family
 !
 address-family l2vpn evpn
  neighbor $peer_group activate
 exit-address-family
!
! Route maps
! Allow all routes from BGP neighbors
route-map ALLOW-ALL permit 10
 set src $router_id
!
ip protocol bgp route-map ALLOW-ALL
EOF

    # Add redistribute route-map if specified
    if [[ -n "$redistribute_route_map" && "$redistribute_route_map" != "ALLOW-ALL" ]]; then
        if [[ -n "$redistribute_interfaces" ]]; then
            cat <<EOF
! Redistribute only connected routes from specified interfaces
! Each interface needs a separate route-map permit entry
EOF
            # Create separate permit entry for each interface
            local seq=10
            for iface in $redistribute_interfaces; do
                cat <<EOF
route-map $redistribute_route_map permit $seq
 match interface $iface
!
EOF
                seq=$((seq + 10))
            done
        else
            cat <<EOF
route-map $redistribute_route_map permit 10
!
EOF
        fi
    fi

    cat <<EOF
line vty
!
end
EOF
}

# Generate FRR config specifically for hypervisors (redistributes only specified interfaces)
# Usage: generate_frr_hypervisor_config <device_name> <router_id> <asn> <neighbors> [redistribute_interfaces]
# Parameters:
#   redistribute_interfaces - Optional: space-separated list of interfaces to redistribute
#                             (default: "lo1 dum-ex")
generate_frr_hypervisor_config() {
    local device_name="$1"
    local router_id="$2"
    local asn="$3"
    local neighbors="$4"
    local redistribute_interfaces="${5:-lo1 dum-ex}"

    FRR_REDISTRIBUTE_ROUTE_MAP="REDISTRIBUTE-CONNECTED" \
    FRR_REDISTRIBUTE_INTERFACES="$redistribute_interfaces" \
    generate_frr_config "$device_name" "$router_id" "$asn" "$neighbors"
}

# Generate FRR config specifically for switches (redistributes all connected)
# Usage: generate_frr_switch_config <device_name> <router_id> <asn> <neighbors>
generate_frr_switch_config() {
    local device_name="$1"
    local router_id="$2"
    local asn="$3"
    local neighbors="$4"

    FRR_REDISTRIBUTE_ROUTE_MAP="" \
    generate_frr_config "$device_name" "$router_id" "$asn" "$neighbors"
}

