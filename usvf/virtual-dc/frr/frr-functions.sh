# Validate device configuration has required fields
# Usage: validate_frr_device_config <config_file> <device_index>
# Returns: 0 if valid, 1 if invalid
validate_frr_device_config() {
    local config_file="$1"
    local device_index="$2"
    local errors=0

    local name=$(yq eval ".frr_config.devices[$device_index].name" "$config_file")
    local host=$(yq eval ".frr_config.devices[$device_index].host" "$config_file")
    local router_id=$(yq eval ".frr_config.devices[$device_index].router_id" "$config_file")
    local asn=$(yq eval ".frr_config.devices[$device_index].asn" "$config_file")

    if [[ -z "$name" || "$name" == "null" ]]; then
        frr_log_error "Device $device_index: missing 'name'"
        errors=$((errors + 1))
    fi

    if [[ -z "$host" || "$host" == "null" ]]; then
        frr_log_error "Device $device_index: missing 'host'"
        errors=$((errors + 1))
    fi

    if [[ -z "$router_id" || "$router_id" == "null" ]]; then
        frr_log_error "Device $device_index: missing 'router_id'"
        errors=$((errors + 1))
    fi

    if [[ -z "$asn" || "$asn" == "null" ]]; then
        frr_log_error "Device $device_index: missing 'asn'"
        errors=$((errors + 1))
    fi

    if [[ $errors -gt 0 ]]; then
        return 1
    fi

    return 0
}

# Validate VDC configuration file
# Usage: validate_vdc_config <vdc_config_file>
# Returns: 0 if valid, 1 if invalid
validate_vdc_config() {
    local vdc_config="$1"

    if [[ ! -f "$vdc_config" ]]; then
        frr_log_error "VDC config file not found: $vdc_config"
        return 1
    fi

    local dc_name=$(yq eval '.global.datacenter_name' "$vdc_config" 2>/dev/null)
    if [[ -z "$dc_name" || "$dc_name" == "null" ]]; then
        frr_log_error "VDC config missing 'global.datacenter_name'"
        return 1
    fi

    return 0
}
